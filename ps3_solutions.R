log_line <- function(...) {
  txt <- paste0(...)
  cat(txt, "\n", sep = "")
  cat(txt, "\n", file = log_file, append = TRUE, sep = "")
}
f2 <- function(x, d = 2) formatC(x, format = "f", digits = d)

# Helpers ---------------------------------------------------------------------
control_mean <- function(data, var, z) mean(data[[var]][data[[z]] == 0])
robust_F     <- function(m, z) unname((coef(m)[z] / se(m)[z])^2)

# Writes a LaTeX table with etable: robust SEs in parentheses, no stars,
# N, adjusted R2, control-group mean of the dependent variable and (optionally)
# the first-stage F-statistic.
write_table <- function(models, file, title, label, headers, keep, dict,
                        ctrl_means, Fstats = NULL, F_label = "F-stat") {
  extra <- list("_Mean dep. var. in control" = f2(ctrl_means))
  if (!is.null(Fstats)) extra[[paste0("_", F_label)]] <- f2(Fstats)
  etable(models,
         tex = TRUE, file = file, replace = TRUE,
         title = title, label = label,
         headers = headers, keep = keep, dict = dict, depvar = FALSE,
         digits = 3, digits.stats = 3,
         fitstat = ~ n + ar2,
         signif.code = NA,
         extralines = extra,
         notes = "Heteroskedasticity-robust (EHW) standard errors in parentheses. Stars suppressed.",
         style.tex = style.tex("aer"))
}

dict <- c(Z_1 = "$Z_1$", Z_2 = "$Z_2$", Z_3 = "$Z_3$",
          fit_cal_int = "Caloric intake", cal_int = "Caloric intake")

################################################################################
# Exercise 3: first stage of Z_1
################################################################################
d1 <- read_csv("ps3_data/ps3_d1.csv", show_col_types = FALSE)

fs1 <- as.list(feols(c(food_exp, cal_int) ~ Z_1, data = d1, vcov = "hetero"))
fs1_mean <- map_dbl(c("food_exp", "cal_int"), ~ control_mean(d1, .x, "Z_1"))
fs1_F    <- map_dbl(fs1, robust_F, z = "Z_1")

write_table(fs1, "tables/tab1_fs_z1.tex",
            title = "First stage of the $Z_1$ instrument", label = "tab:fs_z1",
            headers = c("Food exp.", "Caloric intake"), keep = "Z_1", dict = dict,
            ctrl_means = fs1_mean, Fstats = fs1_F)

log_line("== Exercise 3 (ps3_d1.csv, N = ", nrow(d1), ")")
walk2(fs1, c("food_exp", "cal_int"), function(m, v) {
  log_line(sprintf("  %-9s on Z_1: coef = %.3f, robust SE = %.3f, F = %.2f, control mean = %.2f",
                   v, coef(m)["Z_1"], se(m)["Z_1"], robust_F(m, "Z_1"),
                   control_mean(d1, v, "Z_1")))
})

