################################################################################
# Exercise 5: ITT, 2SLS and weak-IV robust inference
################################################################################
d3 <- read_csv("ps3_data/ps3_d3.csv", show_col_types = FALSE)
log_line("\n== Exercise 5 (ps3_d3.csv, N = ", nrow(d3), ")")

## 5.2 ITT ---------------------------------------------------------------------
itt <- feols(prod ~ Z_3, data = d3, vcov = "hetero")
mean_prod_c <- control_mean(d3, "prod", "Z_3")
write_table(itt, "tables/tab4_itt.tex",
            title = "ITT estimates", label = "tab:itt",
            headers = "Productivity", keep = "Z_3", dict = dict,
            ctrl_means = mean_prod_c)
log_line(sprintf("  ITT: coef = %.2f, robust SE = %.2f, t = %.2f, control mean prod = %.2f",
                 coef(itt)["Z_3"], se(itt)["Z_3"], coef(itt)["Z_3"] / se(itt)["Z_3"],
                 mean_prod_c))

## 5.6(a) First stage -----------------------------------------------------------
fs3 <- feols(cal_int ~ Z_3, data = d3, vcov = "hetero")
F3  <- robust_F(fs3, "Z_3")
mean_cal_c <- control_mean(d3, "cal_int", "Z_3")
write_table(fs3, "tables/tab6_fs_z3.tex",
            title = "First stage of the $Z_3$ instrument", label = "tab:fs_z3",
            headers = "Caloric intake", keep = "Z_3", dict = dict,
            ctrl_means = mean_cal_c, Fstats = F3)
log_line(sprintf("  First stage: coef = %.2f, robust SE = %.2f, robust F = %.2f, control mean cal_int = %.2f",
                 coef(fs3)["Z_3"], se(fs3)["Z_3"], F3, mean_cal_c))

## 5.4 2SLS ----------------------------------------------------------------------
iv <- feols(prod ~ 1 | cal_int ~ Z_3, data = d3, vcov = "hetero")
b_iv  <- unname(coef(iv)["fit_cal_int"])
se_iv <- unname(se(iv)["fit_cal_int"])
ci_iv <- b_iv + c(-1, 1) * qnorm(0.975) * se_iv
write_table(iv, "tables/tab5_iv.tex",
            title = "2SLS estimate", label = "tab:iv",
            headers = "Productivity", keep = "%cal_int", dict = dict,
            ctrl_means = mean_prod_c, Fstats = F3, F_label = "First-stage F-stat")
log_line(sprintf("  2SLS: beta = %.3f, robust SE = %.4f, 95%% CI = [%.3f, %.3f]",
                 b_iv, se_iv, ci_iv[1], ci_iv[2]))

## 5.5 Wald estimator = ITT / first stage ---------------------------------------
wald <- unname(coef(itt)["Z_3"] / coef(fs3)["Z_3"])
log_line(sprintf("  Wald check: ITT / FS = %.2f / %.2f = %.4f (2SLS = %.4f)",
                 coef(itt)["Z_3"], coef(fs3)["Z_3"], wald, b_iv))

## 5.6(b) Anderson-Rubin CI (heteroskedasticity-robust, test inversion) ---------
# For a candidate beta_0, AR regresses prod - beta_0 * cal_int on Z_3 and tests
# that the coefficient is zero. The coefficient is a - beta_0 * b (ITT minus
# beta_0 times first stage) and its robust variance is
# V_aa - 2 beta_0 V_ab + beta_0^2 V_bb, so the acceptance region
# (a - beta_0 b)^2 <= c * Var(beta_0) is a quadratic inequality in beta_0.
X  <- cbind(1, d3$Z_3)
XX <- solve(crossprod(X))
e_y <- resid(lm(prod ~ Z_3, data = d3))
e_x <- resid(lm(cal_int ~ Z_3, data = d3))
hc0_cov <- function(u, v) (XX %*% crossprod(X * u, X * v) %*% XX)[2, 2]  # HC0
V_aa <- hc0_cov(e_y, e_y); V_bb <- hc0_cov(e_x, e_x); V_ab <- hc0_cov(e_y, e_x)
a  <- unname(coef(itt)["Z_3"]); b <- unname(coef(fs3)["Z_3"])
cc <- qchisq(0.95, df = 1)
# (b^2 - c V_bb) beta^2 - 2 (a b - c V_ab) beta + (a^2 - c V_aa) <= 0
A <- b^2 - cc * V_bb; B <- -2 * (a * b - cc * V_ab); C <- a^2 - cc * V_aa
disc <- B^2 - 4 * A * C
stopifnot(A > 0, disc > 0)   # bounded interval (holds iff the robust FS F > 3.84)
ci_ar <- sort((-B + c(-1, 1) * sqrt(disc)) / (2 * A))
# AR p-value for beta_0 = 0 is the robust ITT test (with HC0)
p_ar0 <- 2 * pnorm(-abs(a / sqrt(V_aa)))
log_line(sprintf("  AR 95%% CI = [%.3f, %.3f] (width %.3f vs conventional width %.3f); AR p-value for beta = 0: %.4f",
                 ci_ar[1], ci_ar[2], diff(ci_ar), diff(ci_iv), p_ar0))

## 5.6(c) Lee et al. (2022) tF CI -------------------------------------------------
# Adjustment factors for a 5% test from Table 3, Panel A of Lee et al. (2022),
# for the two F values bracketing ours (same values as in last year's solutions,
# which used Table 3a of the 2021 NBER working paper).
lee_tab <- tibble::tibble(F = c(17.810, 19.178), r = c(1.376, 1.345))
stopifnot(F3 >= lee_tab$F[1], F3 <= lee_tab$F[2])
w     <- (F3 - lee_tab$F[1]) / diff(lee_tab$F)
r_F   <- lee_tab$r[1] + w * diff(lee_tab$r)
ci_tf <- b_iv + c(-1, 1) * qnorm(0.975) * se_iv * r_F
p_conv <- 2 * pnorm(-abs(b_iv / se_iv))
log_line(sprintf("  Lee et al.: F = %.2f lies %.0f%% of the way from %.3f to %.3f; r(F) = %.3f + %.2f*(%.3f - %.3f) = %.3f",
                 F3, 100 * w, lee_tab$F[1], lee_tab$F[2], lee_tab$r[1], w,
                 lee_tab$r[2], lee_tab$r[1], r_F))
log_line(sprintf("  tF 95%% CI = %.3f +/- 1.96 * %.4f * %.3f = [%.3f, %.3f] (width %.3f)",
                 b_iv, se_iv, r_F, ci_tf[1], ci_tf[2], diff(ci_tf)))
log_line(sprintf("  Conventional t = %.2f, conventional p = %.5f; tF rejects beta = 0 at 5%% iff |t| > 1.96*r(F) = %.3f",
                 b_iv / se_iv, p_conv, qnorm(0.975) * r_F))
